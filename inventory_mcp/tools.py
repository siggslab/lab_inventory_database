from .service import Conflict, NotFound, Service, ServiceError, ValidationError

INSTRUCTIONS = f"""
Lab inventory over CSV files. Stored things are 'items' -- samples, reagents,
kits, consumables -- each with one row in items plus a class-specific extension
row. Storage locations form a tree of containers (freezer > shelf > rack > box);
an item points at its container and optionally a well position.

Conventions worth knowing before calling anything:
- ids are opaque and generated by the server (smp_xxxxxxxx). Never invent one;
  search first. Human names and GML sample ids are mutable labels, not keys.
- positions are a bonus. Most entries are recorded at box level only. An absent
  position does NOT mean the well is free.
- measurements are immutable observations. Corrections append via
  correct_measurement rather than editing a value. Every measurement names an
  assay and a unit; the unit must match the assay's quantity.
- status is present / partially_consumed / consumed. A consumed item holds no
  slot, so setting it clears the location.
- writes validate before touching storage. If a call is refused, the message
  lists every rule violated and nothing has been written.
- container kinds: freezer fridge ln2_shipper shelf rack box bench room other.
- run_query SQL sees the 12 tables (items, samples, reagents, kits, consumables,
  containers, patients, projects, patient_projects, item_links, assays,
  measurements) plus views items_wide and latest_measurements.
"""


def _drop_titles(schema: Any) -> None:
    """Delete pydantic's derived ``title`` keys from a JSON schema, in place."""
    if isinstance(schema, dict):
        schema.pop("title", None)
        for value in schema.values():
            _drop_titles(value)
    elif isinstance(schema, list):
        for value in schema:
            _drop_titles(value)


class _Server(MCPServer):
    """``MCPServer`` that ships lean schemas and unindented descriptions.

    Two things pydantic and Python put on the wire that carry no information for a
    caller. ``model_json_schema`` writes ``title: "Item Id"`` next to every
    ``item_id`` and a ``<tool>Arguments`` title on the root; they restate the field
    name below them. And docstrings are indented four spaces because that is where
    they live, so every continuation line of every description arrives carrying that
    padding -- which is re-sent into every context window that lists these tools.

    Both are stripped at the advertise boundary. Argument checking runs against the
    generated model and the original function, never against what is sent out here,
    so a call is validated exactly as before.
    """

    async def list_tools(self) -> list[MCPTool]:
        tools = await super().list_tools()
        for tool in tools:
            _drop_titles(tool.input_schema)
            tool.description = inspect.cleandoc(tool.description)
        return tools


mcp = _Server(
    "lab-inventory",
    version=__version__,
    instructions=INSTRUCTIONS.strip(),
)

_service: Optional[Service] = None


def get_service() -> Service:
    global _service
    if _service is None:
        cfg_path = os.environ.get("INVENTORY_MCP_CONFIG")
        _service = Service.open(path=cfg_path) if cfg_path else Service.open()
    return _service


def set_service(service: Service) -> None:
    """Injection for tests and the CLI."""
    global _service
    _service = service


def _dump(payload: Any) -> str:
    return json.dumps(payload, indent=2, default=str)


def _guard(fn):
    """Turn service exceptions into readable tool errors.

    ``functools.wraps`` is load-bearing rather than cosmetic: the SDK derives each
    tool's input schema from the decorated callable's signature, and a bare
    ``(*args, **kwargs)`` wrapper would advertise nonsense parameters to the model
    instead of the real ones.
    """

    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        try:
            result = fn(*args, **kwargs)
            if hasattr(result, "as_dict"):
                return _dump(result.as_dict())
            return _dump(result)
        except ValidationError as e:
            return "WRITE REFUSED — nothing was saved.\n" + "\n".join(
                "  - " + str(v) for v in e.violations
            )
        except (NotFound, Conflict) as e:
            return f"{type(e).__name__}: {e}"
        except ServiceError as e:
            return f"ERROR: {e}"

    return wrapper


